const fs = require('fs');
const path = require('path');

const fontsDir = path.resolve(__dirname, '..', 'fonts', 'NEW');
const outDir = path.resolve(__dirname, '..', 'fonts');
const outFile = path.join(outDir, 'fonts.css');

const weightMap = {
  thin: 100,
  hairline: 100,
  extralight: 200,
  ultralight: 200,
  light: 300,
  regular: 400,
  normal: 400,
  book: 400,
  medium: 500,
  semibold: 600,
  demi: 600,
  bold: 700,
  extrabold: 800,
  heavy: 900,
  black: 900,
};

function extToFormat(ext) {
  if (ext === '.woff2') return 'woff2';
  if (ext === '.woff') return 'woff';
  if (ext === '.ttf') return 'truetype';
  if (ext === '.otf') return 'opentype';
  if (ext === '.eot') return 'embedded-opentype';
  return '';
}

function detectWeight(part) {
  if (!part) return null;
  const lower = part.toLowerCase();
  if (/^\d{3}$/.test(lower)) return parseInt(lower, 10);
  if (weightMap[lower]) return weightMap[lower];
  return null;
}

function normalizeFamilyName(parts, cutIndex) {
  return parts.slice(0, cutIndex).join(' ').replace(/\s+/g, ' ').trim();
}

if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

if (!fs.existsSync(fontsDir)) {
  console.warn('Warning: fonts directory not found:', fontsDir);
  fs.writeFileSync(outFile, '/* No fonts found; place fonts in fonts/NEW and rerun */\n');
  console.log('Wrote', outFile);
  process.exit(0);
}

const files = fs.readdirSync(fontsDir).filter(f => /\.(woff2|woff|ttf|otf|eot)$/i.test(f));
if (files.length === 0) {
  console.warn('No font files found in', fontsDir);
  fs.writeFileSync(outFile, '/* No font files found in fonts/NEW */\n');
  console.log('Wrote', outFile);
  process.exit(0);
}

// group by family|style|weight
const groups = {}; // key => { family, weight, style, files: [{file, ext, format}] }

files.forEach(file => {
  const ext = path.extname(file).toLowerCase();
  const name = path.basename(file, ext);
  // split on common separators
  const parts = name.split(/[-_ ]+/);
  let style = 'normal';
  // detect italic
  const italicIndex = parts.findIndex(p => /italic/i.test(p));
  if (italicIndex !== -1) {
    style = 'italic';
    parts.splice(italicIndex, 1);
  }

  // detect weight from last part (or second-last)
  let weight = null;
  for (let i = parts.length - 1; i >= Math.max(0, parts.length - 2); i--) {
    const w = detectWeight(parts[i]);
    if (w) {
      weight = w;
      parts.splice(i, 1);
      break;
    }
  }

  // fallback: if any part matches known weight words
  if (!weight) {
    for (let i = parts.length - 1; i >= 0; i--) {
      const w = detectWeight(parts[i]);
      if (w) {
        weight = w;
        parts.splice(i, 1);
        break;
      }
    }
  }

  if (!weight) weight = 400;

  const family = normalizeFamilyName(parts, parts.length) || 'Unnamed';
  const key = `${family}||${weight}||${style}`;
  groups[key] = groups[key] || { family, weight, style, files: [] };
  groups[key].files.push({ file, ext, format: extToFormat(ext) });
});

let css = '/* Generated by scripts/generate-fonts-css.js */\n\n';
for (const k of Object.keys(groups)) {
  const g = groups[k];
  // sort files to prefer woff2, woff, ttf, otf, eot
  const order = { woff2: 0, woff: 1, truetype: 2, opentype: 3, 'embedded-opentype': 4 };
  g.files.sort((a, b) => (order[a.format] || 9) - (order[b.format] || 9));
  const src = g.files.map(f => `url('../fonts/NEW/${f.file}') format('${f.format}')`).join(',\n       ');

  css += `@font-face {\n`;
  css += `  font-family: '${g.family}';\n`;
  css += `  src: ${src};\n`;
  css += `  font-weight: ${g.weight};\n`;
  css += `  font-style: ${g.style};\n`;
  css += `  font-display: swap;\n`;
  css += `}\n\n`;
}

fs.writeFileSync(outFile, css);
console.log('Wrote', outFile);
